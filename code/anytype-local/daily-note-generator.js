#!/usr/bin/env node
/**
 * Daily Note Generator - Creates daily summary in AnyType
 * 
 * Reads OpenClaw workspace files, generates summary, and syncs to AnyType
 * 
 * Usage:
 *   node daily-note-generator.js [--date YYYY-MM-DD]
 * 
 * Environment:
 *   ANYTYPE_API_KEY, ANYTYPE_SPACE_ID, ANYTYPE_API_URL
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const WORKSPACE_DIR = process.env.HOME + '/.openclaw/workspace';
const MEMORY_DIR = WORKSPACE_DIR + '/memory';

function getYesterdayDate() {
  const d = new Date();
  d.setDate(d.getDate() - 1);
  return d.toISOString().split('T')[0];
}

function formatDate(dateStr) {
  const d = new Date(dateStr);
  return d.toLocaleDateString('en-US', { 
    weekday: 'long', 
    year: 'numeric', 
    month: 'long', 
    day: 'numeric' 
  });
}

function readDailyMemory(dateStr) {
  const file = path.join(MEMORY_DIR, `${dateStr}.md`);
  if (!fs.existsSync(file)) return null;
  return fs.readFileSync(file, 'utf-8');
}

function generateDailyNote(dateStr) {
  const displayDate = formatDate(dateStr);
  const memoryContent = readDailyMemory(dateStr) || 'No daily notes recorded.';
  
  // Get git activity
  let gitActivity = '';
  try {
    const gitLog = execSync('cd ~/.openclaw/workspace && git log --oneline -5 --since="24 hours ago" 2>/dev/null || echo ""', { encoding: 'utf-8', timeout: 5000 });
    if (gitLog.trim()) {
      gitActivity = `\n## Git Activity\n\`\`\`\n${gitLog}\n\`\`\`\n`;
    }
  } catch (e) {}

  const content = `# Daily Summary - ${displayDate}

**Date:** ${dateStr}  
**Generated by:** OpenClaw 🤖

## Activity Log

${memoryContent}
${gitActivity}
---
*Auto-generated at ${new Date().toISOString()}*
`;

  return { title: `Daily Summary - ${displayDate}`, content, dateStr };
}

async function main() {
  // Parse args
  let dateStr = process.argv.find((arg, i) => process.argv[i-1] === '--date') || getYesterdayDate();
  
  const note = generateDailyNote(dateStr);
  
  // Save to temp file
  const tempFile = `/tmp/daily-note-${dateStr}.md`;
  fs.writeFileSync(tempFile, note.content);
  
  console.log(`📝 Generated: ${note.title}`);
  
  // Sync to AnyType
  const syncScript = path.join(__dirname, 'sync-to-anytype.js');
  const cmd = `node "${syncScript}" "${tempFile}"`;
  
  try {
    const result = execSync(cmd, { encoding: 'utf-8' });
    console.log(result);
    fs.unlinkSync(tempFile); // Clean up
    console.log('✅ Daily note synced to AnyType');
  } catch (err) {
    console.error('❌ Sync failed:', err.message);
    console.log(`   Temp file: ${tempFile}`);
    process.exit(1);
  }
}

main().catch(err => {
  console.error('Fatal error:', err);
  process.exit(1);
});
